import { test, expect } from '@playwright/test';

test('desktop and mobile journal, edits, photos, angle tool and exports', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await expect(page.locator('.auth-form h2')).toBeVisible();
  if (await page.getByText('Let’s take the first step.').isVisible()) {
    await page.getByLabel('What should we call you?').fill('Enoch');
    await page.getByLabel('Rehab start date').fill('2026-10-07');
    await page.getByLabel('Create a password').fill('browser-test-password');
    await page.getByLabel('Confirm password').fill('browser-test-password');
    await page.getByRole('button', { name: 'Create my journal' }).click();
  } else {
    await page.getByLabel('Password', { exact: true }).fill('browser-test-password');
    await page.getByRole('button', { name: 'Open my journal' }).click();
  }
  await expect(page.getByRole('heading', { name: 'One step at a time, Enoch.' })).toBeVisible();
  await expect(page.locator('.inline-count')).toHaveText('32 entries');
  await expect(page.locator('.stat-value').first()).toContainText('38.3');
  await expect(page.locator('.recharts-line')).toHaveCount(3);
  await page.screenshot({ path: 'test-results/desktop-overview.png', fullPage: true });
  await page.getByRole('button', { name: 'Log today’s progress' }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByLabel('Flexion (bend)').fill('110');
  await page.getByLabel('Anything to remember?').fill('Browser smoke check: edited without losing measurements.');
  await page.getByRole('button', { name: 'Symptoms & activity' }).click();
  await page.getByLabel('Pain at rest').fill('0');
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.locator('.stat-value').last()).toContainText('110');
  await page.getByRole('button', { name: 'Trends & insights', exact: true }).click();
  await page.getByLabel('Difference vs other leg').check();
  await expect(page.locator('.chart-footnote')).toContainText('same-day paired');
  await page.getByRole('button', { name: 'Range of motion', exact: true }).click();
  await expect(page.locator('.chart-wrap')).toBeVisible();
  await page.getByRole('button', { name: 'Daily journal', exact: true }).click();
  await page.getByRole('button', { name: 'All time', exact: true }).click();
  await expect(page.locator('.journal-entry')).toHaveCount(32);
  await page.getByLabel('Search journal').fill('Browser smoke check');
  await expect(page.locator('.journal-entry')).toHaveCount(1);
  const download = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Export CSV', exact: true }).click();
  expect((await download).suggestedFilename()).toBe('stride-entries.csv');
  await page.getByRole('button', { name: 'Add entry', exact: true }).click();
  await page.getByLabel('Entry date').fill('2026-10-06');
  await page.getByLabel('Anything to remember?').fill('Historical entry browser test');
  await page.getByRole('button', { name: 'Save entry', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByLabel('Search journal').fill('Historical entry browser test');
  await expect(page.locator('.journal-entry')).toHaveCount(1);
  await page.getByRole('button', { name: 'Delete entry from 6 October 2026' }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Delete entry', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByLabel('Search journal').fill('');
  await expect(page.locator('.journal-entry')).toHaveCount(32);
  await page.getByRole('button', { name: 'Photo journal', exact: true }).click();
  await page.getByRole('button', { name: 'Add photo', exact: true }).click();
  const image = await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 640; canvas.height = 480;
    const ctx = canvas.getContext('2d')!; ctx.fillStyle = '#e5ebdf'; ctx.fillRect(0, 0, 640, 480);
    return canvas.toDataURL('image/png').split(',')[1];
  });
  await page.locator('input[type=file]').setInputFiles({ name: 'side-view.png', mimeType: 'image/png', buffer: Buffer.from(image, 'base64') });
  await page.getByRole('dialog').getByLabel('Note', { exact: true }).fill('Side-on browser test');
  await page.getByRole('button', { name: 'Save photo', exact: true }).click();
  await expect(page.locator('.photo-card')).toHaveCount(1);
  await page.locator('.photo-card').click();
  await expect(page.locator('.measurement-stage img')).toHaveJSProperty('naturalWidth', 640);
  await page.getByLabel('Measurement type', { exact: true }).selectOption('flexion');
  const thigh = page.getByRole('button', { name: 'Thigh arm handle', exact: true });
  await thigh.focus(); await thigh.press('ArrowUp');
  await expect(page.locator('.angle-summary')).toContainText('Estimated flexion');
  await page.getByRole('button', { name: 'Save alignment only', exact: true }).click();
  await expect(page.locator('.photo-card')).toContainText('° flexion');
  await page.locator('.photo-card').click();
  await page.getByRole('button', { name: 'Delete photo', exact: true }).click();
  await page.getByRole('button', { name: 'Yes, delete', exact: true }).click();
  await expect(page.locator('.photo-card')).toHaveCount(0);
  await page.getByRole('button', { name: 'Settings & data', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Integrations', exact: true })).toBeVisible();
  const backup = page.waitForEvent('download');
  await page.getByRole('link', { name: /Portable journal archive/ }).click();
  expect((await backup).suggestedFilename()).toBe('stride-backup.zip');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await page.getByRole('button', { name: 'Overview', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'One step at a time, Enoch.' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await expect(page.locator('.sidebar')).toHaveCSS('transform', 'matrix(1, 0, 0, 1, -225, 0)');
  if (await page.getByRole('button', { name: 'Dismiss notification' }).isVisible()) await page.getByRole('button', { name: 'Dismiss notification' }).click();
  await page.screenshot({ path: 'test-results/mobile-overview.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Log today’s progress' }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  expect(await page.getByRole('dialog').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
  await page.getByRole('button', { name: 'Close dialog' }).click();
  expect(errors).toEqual([]);
});
