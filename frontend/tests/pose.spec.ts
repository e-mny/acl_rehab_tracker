import { test, expect } from '@playwright/test';

test('local detection, landmark correction, review and conflict-safe daily logging', async ({ page }) => {
  test.skip(!process.env.STRIDE_POSE_TEST_IMAGE, 'Provide a side-on test image and enable the local pose worker.');
  await page.goto('/');
  await expect(page.locator('.auth-form h2')).toBeVisible();
  await page.getByLabel('Password', { exact: true }).fill('browser-test-password');
  await page.getByRole('button', { name: 'Open my journal' }).click();
  await page.getByRole('button', { name: 'Photo journal', exact: true }).click();
  await page.getByRole('button', { name: 'Add photo', exact: true }).click();
  await page.locator('input[type=file]').setInputFiles(process.env.STRIDE_POSE_TEST_IMAGE!);
  await page.getByLabel('Upload measurement type').selectOption('flexion');
  await page.getByLabel('Upload leg in photo').selectOption('left');
  await page.getByRole('dialog').getByLabel('Note', { exact: true }).fill('Pose integration QA');
  await page.getByRole('button', { name: 'Save photo', exact: true }).click();
  const card = page.locator('.photo-card').filter({ hasText: 'Pose integration QA' });
  await expect(card).toContainText('Alignment ready to review', { timeout: 45000 });
  await card.click();
  await expect(page.getByText(/Local model: MediaPipe Pose Landmarker Lite/)).toBeVisible();
  await expect(page.getByRole('button', { name: 'Save flexion measurement', exact: true })).toBeDisabled();
  const hip = page.getByRole('button', { name: 'Thigh arm handle', exact: true });
  const before = Number(await hip.getAttribute('cx'));
  await hip.focus(); await hip.press('ArrowRight');
  expect(Number(await hip.getAttribute('cx'))).toBeGreaterThan(before);
  await page.getByLabel('I reviewed the measurement type, leg, alignment and angle.').check();
  await page.getByRole('button', { name: 'Save flexion measurement', exact: true }).click();
  await expect(page.locator('.measurement-preview')).toContainText('Replace 110°');
  const rows = await (await page.request.get('/api/entries')).json();
  const last = rows.at(-1);
  await page.request.patch('/api/entries/by-date/'+last.date, { data: { pain_activity: 4 }, headers: { 'X-Stride-Request': '1' } });
  await page.getByRole('button', { name: 'Confirm replacement', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('changed since your preview');
  await page.getByRole('button', { name: 'Save flexion measurement', exact: true }).click();
  await expect(page.locator('.measurement-preview')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Confirm replacement', exact: true })).toBeEnabled();
  await page.screenshot({ path: 'test-results/pose-review.png', fullPage: true });
  await page.getByRole('button', { name: 'Confirm replacement', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const photo = (await (await page.request.get('/api/photos')).json()).find((p: { caption: string }) => p.caption === 'Pose integration QA');
  expect(photo.measurements).toHaveLength(1);
  expect(photo.measurements[0].model_version).toContain('mediapipe-1.2.2');
  const updated = (await (await page.request.get('/api/entries')).json()).find((e: { date: string }) => e.date === last.date);
  expect(updated.flexion).toBe(photo.angle);
  expect(updated.knee).toBe(last.knee);
  expect(updated.notes).toBe(last.notes);
  expect(updated.pain_activity).toBe(4);
});
