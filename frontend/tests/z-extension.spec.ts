import { test, expect } from '@playwright/test';

test('cropped-photo fallback, precise extension alignment and batch proposals', async ({ page }) => {
  test.skip(!process.env.STRIDE_POSE_TEST_IMAGE, 'Enable the local pose worker for fallback and queue checks.');
  await page.goto('/');
  await expect(page.locator('.auth-form h2')).toBeVisible();
  await page.getByLabel('Password', { exact: true }).fill('browser-test-password');
  await page.getByRole('button', { name: 'Open my journal' }).click();
  await page.getByRole('button', { name: 'Photo journal', exact: true }).click();
  await page.request.patch('/api/entries/by-date/2026-11-06', { data: { flexion: 6 }, headers: { 'X-Stride-Request': '1' } });
  const before = (await (await page.request.get('/api/entries')).json()).find((e: { date: string }) => e.date === '2026-11-06');
  const png = await page.evaluate(() => { const c = document.createElement('canvas'); c.width = 640; c.height = 480; const ctx = c.getContext('2d')!; ctx.fillStyle = '#c7d1c0'; ctx.fillRect(0,0,640,480); return c.toDataURL('image/png').split(',')[1]; });
  await page.getByRole('button', { name: 'Add photo', exact: true }).click();
  await page.locator('input[type=file]').setInputFiles({ name: 'cropped-leg.png', mimeType: 'image/png', buffer: Buffer.from(png,'base64') });
  await page.getByLabel('Upload measurement type').selectOption('extension');
  await page.getByLabel('Upload leg in photo').selectOption('right');
  await page.getByLabel('Photo date', { exact: true }).fill('2026-11-06');
  await page.getByLabel('Note', { exact: true }).fill('Extension precision QA');
  await page.getByRole('button', { name: 'Save photo', exact: true }).click();
  const card = page.locator('.photo-card').filter({ hasText: 'Extension precision QA' });
  await expect(card).toContainText('Manual alignment needed', { timeout: 45000 });
  await card.click();
  await expect(page.getByText(/No full-body pose was found/)).toBeVisible();
  await expect(page.locator('.angle-summary')).toContainText('Align the arms');
  await page.getByRole('radio', { name: /Beyond straight/ }).check();
  const shin = page.getByRole('button', { name: 'Shin arm handle', exact: true });
  await shin.focus();
  for (let i=0; i<4; i++) await shin.press('Shift+ArrowUp');
  await expect(page.locator('.angle-summary')).toContainText('Extension · hyperextension (negative)');
  await expect(page.locator('.precision-lens')).toBeVisible();
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click();
  await expect(page.getByLabel('Image zoom')).toHaveValue('125');
  await shin.focus();
  const y = Number(await shin.getAttribute('cy'));
  await page.getByRole('button', { name: 'Nudge up', exact: true }).click();
  expect(Number(await shin.getAttribute('cy'))).toBeLessThan(y);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.getByRole('dialog').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
  await page.getByLabel('I reviewed the measurement type, leg, alignment and extension direction.').check();
  await page.screenshot({ path: 'test-results/extension-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Save extension measurement', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const entries = await (await page.request.get('/api/entries')).json();
  const after = entries.find((e: { date: string }) => e.date === '2026-11-06');
  expect(after.extension).toBeLessThan(0);
  expect(after.flexion).toBe(6);
  expect(after.notes).toBe(before.notes);
  expect(after.knee).toBe(before.knee);
  const photos = await (await page.request.get('/api/photos')).json();
  const saved = photos.find((p: { caption: string }) => p.caption === 'Extension precision QA');
  expect(saved.measurements[0].metric).toBe('extension');
  expect(saved.measurements[0].extension_direction).toBe('hyperextension');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: 'Add photo', exact: true }).click();
  await page.locator('input[type=file]').setInputFiles({ name: 'batch.png', mimeType: 'image/png', buffer: Buffer.from(png,'base64') });
  await page.getByLabel('Note', { exact: true }).fill('Batch-only QA');
  await page.getByRole('button', { name: 'Save photo', exact: true }).click();
  await page.getByLabel('Batch analysis leg').selectOption('left');
  await page.getByRole('button', { name: 'Analyse all photos', exact: true }).click();
  await expect(page.locator('.photo-batch-bar')).toContainText('No daily measurements were changed.');
  await expect(page.locator('.photo-card').filter({ hasText: 'Batch-only QA' })).toContainText('Manual alignment needed', { timeout: 45000 });
  expect(await (await page.request.get('/api/entries')).json()).toEqual(entries);
});
